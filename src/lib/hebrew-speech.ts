// §410: 🗣️ הכנת טקסט עברי להקראה בטלפון.
//
// 🐛 מה נשמע רע: הודעת פתיחת מכירת חשון הוקראה כך —
//   "תשפ ז ... י א חשון ... ט חשון ... בשעה 22 00"
// כי sanitizeTts מחליף גרשיים, נקודתיים ונקודות ברווח (הם מפרידים
// בפרוטוקול של ימות). התאריכים העבריים התפרקו לאותיות, השעה לשני
// מספרים, ובין המשפטים לא הייתה שום הפסקה.
//
// הפתרון: לפני הניקוי — לתרגם את מה שנכתב לעין למה שנאמר לאוזן:
//   י"א חשון      → אחד עשר בחשוון
//   22:00         → עשר בלילה
//   10:00-12:00   → עשר בבוקר עד שתים עשרה בצהריים
//   ק"ג, ש"ח, ₪   → קילו, שקלים
//   סוף משפט      → הפסקה אמיתית (מקטע נפרד בימות, נקודה בקול הטבעי)
//
// הקובץ טהור (בלי ימות ובלי מסד) — משמש גם את ההקראה של ימות וגם את
// הקול הטבעי (phone-voice.ts), כדי ששניהם יאמרו בדיוק אותו דבר.

const HEB_LETTER = "א-ת";
const Q = `["״]`; // גרשיים
const G = `['׳]`; // גרש

// ─── מספרים במילים ───

const MASC = ["", "אחד", "שניים", "שלושה", "ארבעה", "חמישה", "שישה", "שבעה", "שמונה", "תשעה", "עשרה"];
const MASC_TEEN = ["", "אחד עשר", "שנים עשר", "שלושה עשר", "ארבעה עשר", "חמישה עשר", "שישה עשר", "שבעה עשר", "שמונה עשר", "תשעה עשר"];
const FEM_HOUR = ["", "אחת", "שתיים", "שלוש", "ארבע", "חמש", "שש", "שבע", "שמונה", "תשע", "עשר", "אחת עשרה", "שתים עשרה"];
const TENS = ["", "", "עשרים", "שלושים"];

/** יום בחודש (1-30) במילים, בזכר — "אחד עשר בחשוון", "עשרים ושניים בכסלו" */
export function dayWords(n: number): string {
  if (n <= 10) return MASC[n] ?? String(n);
  if (n < 20) return MASC_TEEN[n - 10];
  const t = Math.floor(n / 10);
  const u = n % 10;
  return u ? `${TENS[t]} ו${MASC[u]}` : TENS[t];
}

/** גימטריה של יום בחודש: ט → 9, י"א → 11, ט"ו → 15, כ"ב → 22 */
const GEMATRIA: Record<string, number> = {
  א: 1, ב: 2, ג: 3, ד: 4, ה: 5, ו: 6, ז: 7, ח: 8, ט: 9,
  י: 10, כ: 20, ל: 30,
};
function gematriaDay(letters: string): number | null {
  let sum = 0;
  for (const ch of letters) {
    const v = GEMATRIA[ch];
    if (!v) return null;
    sum += v;
  }
  return sum >= 1 && sum <= 30 ? sum : null;
}

const HEB_MONTHS: Record<string, string> = {
  תשרי: "תשרי",
  חשון: "חשוון",
  חשוון: "חשוון",
  מרחשון: "מרחשוון",
  מרחשוון: "מרחשוון",
  כסלו: "כסלו",
  כסליו: "כסלו",
  טבת: "טבת",
  שבט: "שבט",
  אדר: "אדר",
  ניסן: "ניסן",
  אייר: "אייר",
  איר: "אייר",
  סיון: "סיוון",
  סיוון: "סיוון",
  תמוז: "תמוז",
  אב: "אב",
  אלול: "אלול",
};
const HEB_MONTH_RE = Object.keys(HEB_MONTHS)
  .sort((a, b) => b.length - a.length)
  .join("|");

const GREG_MONTHS = ["", "בינואר", "בפברואר", "במרץ", "באפריל", "במאי", "ביוני", "ביולי", "באוגוסט", "בספטמבר", "באוקטובר", "בנובמבר", "בדצמבר"];

/** 22:00 → "עשר בלילה", 9:30 → "תשע וחצי בבוקר" */
export function timeWords(h: number, m: number): string {
  const h12 = h % 12 === 0 ? 12 : h % 12;
  let mins = "";
  if (m === 15) mins = " ורבע";
  else if (m === 30) mins = " וחצי";
  else if (m > 0) mins = ` ו${m} דקות`;
  const period =
    h >= 5 && h < 12 ? "בבוקר"
    : h >= 12 && h < 16 ? "בצהריים"
    : h >= 16 && h < 19 ? "אחר הצהריים"
    : h >= 19 && h < 22 ? "בערב"
    : "בלילה";
  return `${FEM_HOUR[h12]}${mins} ${period}`;
}

// ─── קיצורים ───
// סדר: הארוכים קודם (מוצש"ק לפני ש"ק).
const ABBREVIATIONS: [string, string][] = [
  ["מוצש\"ק", "מוצאי שבת קודש"],
  ["מוצ\"ש", "מוצאי שבת"],
  ["עש\"ק", "ערב שבת קודש"],
  ["ש\"ק", "שבת קודש"],
  ["אחה\"צ", "אחר הצהריים"],
  ["לפנה\"צ", "לפני הצהריים"],
  ["בעז\"ה", "בעזרת השם"],
  ["בע\"ה", "בעזרת השם"],
  ["אי\"ה", "אם ירצה השם"],
  ["בל\"נ", "בלי נדר"],
  ["בס\"ד", ""],
  ["ב\"ה", "ברוך השם"],
  ["ר\"ח", "ראש חודש"],
  ["ק\"ג", "קילו"],
  ["ש\"ח", "שקלים"],
  ["ע\"י", "על ידי"],
  ["ע\"פ", "על פי"],
  ["ת\"ז", "תעודת זהות"],
  ["הנ\"ל", "הנזכר"],
  ["וכו'", "וכולי"],
  ["וכדו'", "וכדומה"],
  ["מס'", "מספר"],
  ["יח'", "יחידות"],
  ["גר'", "גרם"],
  ["רח'", "רחוב"],
  ["טל'", "טלפון"],
];

function escapeRe(s: string) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
const ABBR_RULES = ABBREVIATIONS.map(([from, to]) => {
  // " ו-' מתפרשים גם כגרשיים/גרש העבריים
  const pattern = escapeRe(from).replace(/"/g, Q).replace(/'/g, G);
  // ⚠️ גבול מילה ידני: \b לא עובד על עברית ב-JS
  return {
    re: new RegExp(`(^|[^${HEB_LETTER}])([ובלמהש]?)${pattern}(?![${HEB_LETTER}])`, "g"),
    to,
  };
});

/**
 * הטקסט כפי שצריך להיאמר — עם פיסוק של משפטים (נקודה בסוף כל משפט),
 * אבל בלי תאריכים מקוצרים, שעות בספרות, קיצורים ואימוג'י.
 *
 * ⚠️ הפלט עדיין מכיל נקודות ופסיקים — לימות הוא עובר דרך
 * speechSegments (שמפצל במקום הנקודות), ולקול הטבעי הוא נשלח כמו שהוא.
 */
export function speakableHebrew(input: string): string {
  let s = String(input ?? "");

  // אימוג'י וסמלים — ימות מקריאים אותם בשמם או נתקעים
  s = s.replace(/[\p{Extended_Pictographic}\u{FE0F}\u{200D}\u{20E3}]/gu, " ");
  s = s.replace(/[*_#•►◄|<>[\]{}~^]/g, " ");

  // "בין 18:30-20:00" → "בין שש וחצי אחר הצהריים לשמונה בערב"
  s = s.replace(
    /בין\s+([01]?\d|2[0-3]):([0-5]\d)\s*(?:[-–—]|ל|עד)\s*([01]?\d|2[0-3]):([0-5]\d)(?![\d:])/g,
    (_, h1, m1, h2, m2) => `בין ${timeWords(+h1, +m1)} ל${timeWords(+h2, +m2)}`
  );
  // טווח שעות: 10:00-12:00 / 10:00 עד 12:00
  s = s.replace(
    /(?<![\d:])([01]?\d|2[0-3]):([0-5]\d)\s*(?:[-–—]|עד)\s*([01]?\d|2[0-3]):([0-5]\d)(?![\d:])/g,
    (_, h1, m1, h2, m2) => `${timeWords(+h1, +m1)} עד ${timeWords(+h2, +m2)}`
  );
  // שעה בודדת
  s = s.replace(
    /(?<![\d:])([01]?\d|2[0-3]):([0-5]\d)(?![\d:])/g,
    (_, h, m) => timeWords(+h, +m)
  );

  // תאריך עברי: י"א חשון / ט' בחשון / כ"ב במרחשוון
  s = s.replace(
    new RegExp(
      `(^|[^${HEB_LETTER}])([${HEB_LETTER}]{1,2})(?:${Q}([${HEB_LETTER}])|${G})\\s+(ב)?(${HEB_MONTH_RE})(?![${HEB_LETTER}])`,
      "g"
    ),
    (all, pre, a, b, _b, month) => {
      const n = gematriaDay(a + (b ?? ""));
      if (n === null) return all;
      return `${pre}${dayWords(n)} ב${HEB_MONTHS[month]}`;
    }
  );

  // תאריך לועזי: 20/10, 20/10/2026, 20.10 (לא מחירים: 12.90 ש"ח)
  s = s.replace(
    /(?<![\d.\/])(\d{1,2})[\/.](\d{1,2})(?:[\/.](\d{2,4}))?(?![\d.\/])(?!\s*(?:₪|ש["״]ח|שקל))/g,
    (all, d, m) => {
      const day = +d;
      const mon = +m;
      if (day < 1 || day > 31 || mon < 1 || mon > 12) return all;
      return `${day} ${GREG_MONTHS[mon]}`;
    }
  );

  // מטבע: ₪50 / 50₪ / 50 ש"ח
  s = s.replace(/₪\s*(\d[\d,]*(?:\.\d+)?)/g, "$1 שקלים");
  s = s.replace(/(\d[\d,]*(?:\.\d+)?)\s*₪/g, "$1 שקלים");

  // קיצורים
  for (const r of ABBR_RULES) {
    s = s.replace(r.re, (_, pre, prefix) => `${pre}${prefix}${r.to}`);
  }

  // מספר עשרוני: 1.5 → "1 נקודה 5" (הנקודה היא מפריד בימות)
  s = s.replace(/(\d)\.(\d)/g, "$1 נקודה $2");
  // אלפים: 1,000 → 1000
  s = s.replace(/(\d),(\d{3})(?!\d)/g, "$1$2");

  // מקף בתוך מילה (לך-לך, ב-20) → רווח. מקף עם רווחים → הפסקה קצרה.
  s = s.replace(/\s+[-–—]+\s+/g, ", ");
  s = s.replace(/[-–—]/g, " ");

  // סוף משפט: שורה חדשה, ! ? ; → נקודה. נקודתיים → פסיק.
  s = s.replace(/[!?;]+/g, ".");
  s = s.replace(/\s*\n+\s*/g, ". ");
  s = s.replace(/:/g, ",");

  // גרשיים/גרש שנשארו בתוך מילה (תשפ"ז, ג'ינס) — מצמידים ולא מפרקים
  s = s.replace(new RegExp(`([${HEB_LETTER}])${Q}([${HEB_LETTER}])`, "g"), "$1$2");
  s = s.replace(new RegExp(`([${HEB_LETTER}])${G}`, "g"), "$1");
  s = s.replace(/["'`׳״()]/g, " ");

  // ניקוי פיסוק כפול
  s = s
    .replace(/[ \t]+/g, " ")
    .replace(/\s+([.,])/g, "$1")
    .replace(/([.,])(?:\s*[.,])+/g, (m) => (m.includes(".") ? "." : ","))
    .replace(/^[\s.,]+/, "")
    .trim();
  if (s && !/[.,]$/.test(s)) s += ".";
  return s.replace(/,$/, ".");
}

/**
 * חלוקה למשפטים, כל אחד עד max תווים — לימות.
 *
 * כל משפט נשלח כמקטע t- נפרד: ימות עוצרים בין מקטעים, וזו בדיוק
 * ההפסקה שהייתה חסרה בסוף משפט. משפט ארוך מדי מפוצל בפסיק
 * (MAX_TTS_SEGMENT ב-yemot-lib — מעל ~200 תווים ימות מנתקים).
 */
export function speechSentences(text: string, max = 180): string[] {
  const out: string[] = [];
  for (const raw of speakableHebrew(text).split(/\.\s*/)) {
    const sentence = raw.trim();
    if (!sentence) continue;
    if (sentence.length <= max) {
      out.push(sentence);
      continue;
    }
    let cur = "";
    for (const part of sentence.split(/,\s*/)) {
      const next = cur ? `${cur}, ${part}` : part;
      if (next.length > max && cur) {
        out.push(cur);
        cur = part;
      } else {
        cur = next;
      }
    }
    if (cur) out.push(cur.slice(0, max));
  }
  return out;
}
