// §71: זהות הלקוח — מקור אמת אחד.
//
// ═══════════════════════════════════════════════════════════════
// למה הקובץ הזה נוצר
// ═══════════════════════════════════════════════════════════════
// 🐛 באג הכפילויות: היו במערכת **שני** נירמולי טלפון שונים.
//
//   הרשמה / נציג / IVR:  replace(/\D/g,"") + המרת 972 ל-0
//                        "+972-50-1234567"  ->  "0501234567"
//
//   יצירת לקוח ע"י מנהל: replace(/[\s\-()]/g,"") בלבד
//                        "+972-50-1234567"  ->  "+972501234567"
//
// Customer.phone הוא @unique, אבל שתי המחרוזות שונות - ולכן המסד
// לא חסם, ואותו אדם נכנס פעמיים. משם הכל מתגלגל: הנציג לא מוצא
// אותו בחיפוש, יוצר שוב, ובסוף יש שלוש רשומות ושלוש היסטוריות.
//
// ═══════════════════════════════════════════════════════════════
// כלל ברזל
// ═══════════════════════════════════════════════════════════════
// כל מסלול שיוצר או מחפש לקוח - באתר, אצל הנציג, אצל המנהל,
// בטלפון - עובר דרך הפונקציות כאן. אין נירמול מקומי.

/**
 * נירמול טלפון לפורמט האחסון: ספרות בלבד, קידומת מקומית.
 *
 *   "+972-50-123-4567"  ->  "0501234567"
 *   "972501234567"      ->  "0501234567"
 *   "050 123 4567"      ->  "0501234567"
 *   "050-1234567"       ->  "0501234567"
 *
 * 972 מומר ל-0 ולא נשאר: כך מספר שהודבק מוואטסאפ ומספר שהוקלד
 * ידנית מגיעים לאותה מחרוזת, וה-unique של המסד באמת עובד.
 */
export function normalizePhone(raw: unknown): string {
  const digits = String(raw ?? "").replace(/\D/g, "");
  if (digits.startsWith("972")) return "0" + digits.slice(3);
  return digits;
}

/** האם המספר תקין אחרי נירמול (9-10 ספרות ישראליות) */
export function isValidPhone(normalized: string): boolean {
  return /^0\d{8,9}$/.test(normalized);
}

/**
 * כל הווריאציות לחיפוש במסד.
 *
 * נדרש בגלל רשומות ישנות שנשמרו לפני האיחוד ועדיין מכילות פורמט
 * אחר. ברשומות חדשות מספיקה normalizePhone.
 */
export function phoneCandidates(raw: unknown): string[] {
  const trimmed = String(raw ?? "").trim();
  const digits = trimmed.replace(/\D/g, "");
  return Array.from(
    new Set([trimmed, digits, normalizePhone(trimmed), "+" + digits])
  ).filter((v) => v.length > 2);
}

/**
 * ניקוי שם.
 *
 * 🐛 הבאג השני: שמות שהגיעו מזיהוי הדיבור של ה-IVR נשמרו עם תווי
 * כיווניות בלתי-נראים (RLM/LRM) ורווחים לא-שבירים. התוצאה הייתה
 * ש-`LIKE '%בושקפן%'` החזיר אפס שורות על לקוח שקיים - הנציג לא
 * מצא אותו בחיפוש, יצר אותו מחדש, ונוצרה כפילות.
 *
 * התווים מוסרים:
 *   U+200E/U+200F  סימני כיווניות (LRM/RLM)
 *   U+202A-U+202E  סימני הטמעה כיוונית
 *   U+2066-U+2069  בידוד כיווני
 *   U+200B-U+200D  רוחב אפס
 *   U+FEFF         BOM
 *   U+00A0         רווח לא-שביר -> רווח רגיל
 */
export function cleanName(raw: unknown): string {
  return String(raw ?? "")
    .replace(/[\u200E\u200F\u202A-\u202E\u2066-\u2069\u200B-\u200D\uFEFF]/g, "")
    .replace(/\u00A0/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * מפתח השוואה לזיהוי שמות זהים.
 *
 * מסיר גם גרשיים וסדר מילים, כדי ש"אשר בוקשפן" ו"בוקשפן אשר"
 * ייחשבו זהים בבדיקת כפילות. **לא** לאחסון - רק להשוואה.
 */
export function nameKey(raw: unknown): string {
  return cleanName(raw)
    .replace(/["'`׳״]/g, "")
    .toLowerCase()
    .split(" ")
    .filter(Boolean)
    .sort()
    .join(" ");
}

/**
 * §108: ניקוי שם שהגיע מזיהוי הדיבור של ימות.
 *
 * ═══════════════════════════════════════════════════════════════
 * הבאג שנסגר - חמור, והתגלה בשטח
 * ═══════════════════════════════════════════════════════════════
 * לקוח התקשר, אמר "יהודה", הזיהוי נכשל, ימות השמיעו "לא זוהה
 * הדיבור, נתחיל מחדש", והוא אמר שוב. הפרמטר NAME חזר אלינו
 * עם **ההודעות של ימות בתוכו**:
 *
 *   "נתחיל מחדש יהודה"
 *   "לא זו הדיבור יהודה אייזנברג"
 *
 * שני לקוחות נשמרו במסד עם השמות האלה, והמייל לנציג יצא איתם.
 *
 * ═══════════════════════════════════════════════════════════════
 * למה מסירים מההתחלה בלבד
 * ═══════════════════════════════════════════════════════════════
 * ההודעה של ימות תמיד קודמת לדיבור של הלקוח - היא מושמעת, ואז
 * הוא מדבר. שם משפחה אמיתי לא יתחיל ב"נתחיל מחדש".
 *
 * הלולאה חוזרת כי ימות עשויים לצרף כמה ניסיונות: "לא זוהה
 * נתחיל מחדש יהודה" - שתי הודעות ואז השם.
 */
const YEMOT_SYSTEM_PHRASES = [
  "לא זוהה הדיבור",
  "לא זוהה דיבור",
  "לא זו הדיבור",
  "לא זוהה",
  "נתחיל מחדש",
  "אנא אמור את שמך המלא",
  "אנא אמור את שמך",
  "אנא אמור",
  "לאחר הצליל",
  "השם שנקלט",
  "נסה שוב",
];

export function cleanSpokenName(raw: unknown): string {
  let out = cleanName(String(raw ?? "").replace(/^Digits-/, ""));

  // הסרה חוזרת: ימות עשויים לצרף כמה הודעות ברצף לפני השם.
  // התקרה מונעת לולאה אינסופית אם משהו בלתי צפוי חוזר על עצמו.
  for (let i = 0; i < 6; i++) {
    const before = out;
    for (const phrase of YEMOT_SYSTEM_PHRASES) {
      if (out.startsWith(phrase)) {
        out = out.slice(phrase.length).trim();
        // פסיק או נקודה שנשארו אחרי ההסרה
        out = out.replace(/^[,.\-–—\s]+/, "").trim();
      }
    }
    if (out === before) break;
  }

  return out;
}

/**
 * §108: האם השם שנקלט סביר בכלל.
 *
 * שם שנשאר ריק אחרי הניקוי, או שהוא ארוך באופן חריג, מעיד על
 * זיהוי כושל ולא על שם אמיתי. עדיף "לקוח טלפוני" שהנציג יתקן
 * מאשר שם שגוי שנראה אמיתי ואיש לא יבדוק אותו.
 */
export function isPlausibleName(name: string): boolean {
  const n = name.trim();

  // ⚠️ הרף כאן **מכוון להיות נמוך**. המטרה היא לתפוס זיהוי כושל
  // מובהק, לא לשפוט שמות.
  //
  // גרסה ראשונה פסלה שמות מתחת ל-2 תווים ומעל 40, וזו הייתה
  // טעות: "לי" ו"בן" הם שמות אמיתיים, ו"יהודה אריה לייב רוזנברג"
  // מתקרב ל-25. שם שנפסל הופך ל"לקוח טלפוני" - וכשזה קורה
  // לרבים, רשימת הבקשות אצל הנציג מאבדת את כל ערכה.
  //
  // עדיף שם חלקי או משובש קלות, שהנציג רואה ומתקן, מאשר תווית
  // גנרית שמסתירה את המידע לגמרי.

  // ריק בלבד - אין מה לשמור
  if (n.length === 0) return false;

  // תו בודד אינו שם בשום שפה
  if (n.length === 1) return false;

  // רק ספרות/סימנים בלי אף אות - זיהוי שנכשל לגמרי
  if (!/[\u0590-\u05FFa-zA-Z]/.test(n)) return false;

  // ארוך בצורה שאינה אפשרית לשם אנושי (משפט שלם שנקלט). 80 תווים
  // הם כ-12 מילים - מעבר לכל שם, כולל שמות חסידיים ארוכים.
  if (n.length > 80) return false;

  return true;
}
