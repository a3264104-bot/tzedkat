// §152: פרטי כניסה - שדה אחד
// ═══════════════════════════════════════════════════════════════
// עד היום היו שני מנגנונים מקבילים: `loginCode` (6 ספרות) ו-
// `passwordHash` (סיסמה שהלקוח בחר). המנהל ראה שניים, הלקוח לא
// ידע איזה מהם שלו, והטלפון הקריא רק את הראשון.
//
// עכשיו: **ערך אחד**. מה שיש בו תלוי במקור:
//   • נרשם באתר      -> הסיסמה שבחר (אותיות/ספרות)
//   • נרשם בטלפון    -> קוד 6 ספרות שהמערכת הפיקה
//
// ⚠️ המסד לא משתנה. שני השדות נשארים, וההתחברות ממשיכה לבדוק את
// שניהם (§125). מה שהשתנה הוא ש**יש מקור אמת אחד לתצוגה ולהקראה**,
// במקום שכל מסך יחליט לבד מה להראות.

/**
 * ⚠️ איות אותיות לטיניות בעברית.
 *
 * הלקוח שומע את הסיסמה בטלפון, וצריך להקליד אותה באתר. אות
 * לטינית שתוקרא כרצף ("mfkq") אינה מובנת - היא חייבת להיות
 * מאויתת אות-אות.
 *
 * ⚠️ ההגייה נבחרה כדי להיות **מובחנת בשמיעה**, ולא כדי להיות
 * מדויקת. "M" ו-"N" נשמעות דומה באנגלית, ולכן "אֶם" מול "אֶן"
 * מודגשות בעברית עם ניקוד מרומז בכתיב.
 */
const LETTER_HE: Record<string, string> = {
  a: "איי",
  b: "בי",
  c: "סי",
  d: "די",
  e: "אי",
  f: "אף",
  g: "ג'י",
  h: "אייץ'",
  i: "איי",
  j: "ג'יי",
  k: "קיי",
  l: "אל",
  m: "אם",
  n: "אן",
  o: "או",
  p: "פי",
  q: "קיו",
  r: "אר",
  s: "אס",
  t: "טי",
  u: "יו",
  v: "וי",
  w: "דאבל יו",
  x: "אקס",
  y: "וואי",
  z: "זי",
};

/** ספרות בעברית - להקראה אחידה עם האותיות */
const DIGIT_HE: Record<string, string> = {
  "0": "אפס",
  "1": "אחת",
  "2": "שתיים",
  "3": "שלוש",
  "4": "ארבע",
  "5": "חמש",
  "6": "שש",
  "7": "שבע",
  "8": "שמונה",
  "9": "תשע",
};

/**
 * §152: האם הערך הוא ספרות בלבד.
 *
 * קובע איך הוא יוקרא: ספרות רצופות נשמעות טבעי, ואילו ערך מעורב
 * חייב איות אות-אות.
 */
export function isDigitsOnly(value: string): boolean {
  return /^\d+$/.test(value.trim());
}

/**
 * §152: המרת פרטי הכניסה לטקסט להקראה בטלפון.
 *
 * ⚠️ מוחזר טקסט עברי מוכן, לא רצף תווים. ימות מקריאים עברית,
 * ואות לטינית גולמית תישמע כרעש או תידלג.
 *
 * ⚠️ מפריד פסיקים בין התווים: בלעדיו ההקראה רצה יחד והלקוח לא
 * מספיק לכתוב. הפסיק יוצר הפוגה טבעית.
 *
 * דוגמאות:
 *   "482193"   -> "ארבע, שמונה, שתיים, אחת, תשע, שלוש"
 *   "mfkq78"   -> "אם, אף, קיי, קיו, שבע, שמונה"
 */
export function spellForPhone(value: string): string {
  const v = String(value || "").trim();
  if (!v) return "";

  const parts: string[] = [];
  for (const ch of v) {
    const lower = ch.toLowerCase();
    if (DIGIT_HE[lower]) {
      parts.push(DIGIT_HE[lower]);
    } else if (LETTER_HE[lower]) {
      parts.push(LETTER_HE[lower]);
    } else if (ch === "-" || ch === "_") {
      parts.push("מקף");
    } else if (ch === " ") {
      parts.push("רווח");
    }
    // ⚠️ תו לא מוכר **מדולג בשקט**. הקראת "סימן לא ידוע" הייתה
    // מבלבלת יותר מלדלג, והלקוח ממילא לא יידע מה להקליד.
  }
  return parts.join(", ");
}

export type Credential = {
  /** הערך עצמו - מה שהלקוח מקליד */
  value: string;
  /** "code" = הופק ע"י המערכת · "password" = הלקוח בחר */
  kind: "code" | "password";
  /** האם ניתן להקריא אותו בטלפון */
  canSpeak: boolean;
};

/**
 * §152: פרטי הכניסה של הלקוח - מקור אמת אחד.
 *
 * ⚠️ הקוד קודם לסיסמה בכוונה: הוא הופק ע"י המערכת ולכן ודאי
 * תקין, בעוד הסיסמה עשויה להיות ישנה או שנשמרה בגלוי רק מאז
 * §151. לקוח שיש לו שניהם - הקוד הוא מה שנמסור.
 *
 * ⚠️ null פירושו שאין לו שום דרך להיכנס. זו בעיה שצריך להציג
 * למנהל, לא לבלוע.
 */
export function resolveCredential(customer: {
  loginCode?: string | null;
  passwordPlain?: string | null;
}): Credential | null {
  const code = (customer.loginCode || "").trim();
  if (code) {
    return { value: code, kind: "code", canSpeak: true };
  }

  const pw = (customer.passwordPlain || "").trim();
  if (pw) {
    // ⚠️ סיסמה ארוכה מדי אינה ניתנת להקראה מעשית: 20 תווים
    // מאויתים הם חצי דקה שהלקוח לא יצליח לכתוב.
    return { value: pw, kind: "password", canSpeak: pw.length <= 12 };
  }

  return null;
}

/**
 * §152: תווית לתצוגה במסך המנהל.
 *
 * הסבר קצר שאומר למנהל מאיפה הערך הגיע - כדי שידע אם הלקוח
 * מכיר אותו (בחר בעצמו) או שצריך למסור לו.
 */
export function credentialLabel(c: Credential): string {
  return c.kind === "code"
    ? "קוד שהופק — יש למסור ללקוח"
    : "סיסמה שהלקוח בחר בעצמו";
}
