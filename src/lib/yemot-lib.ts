/**
 * §101: הקלטות שכבר בוצעו, מ-ENV.
 *
 * שם שמופיע כאן מוסר מ-TTS_ONLY ומושמע בקול שהוקלט. כך אפשר
 * להקליט בקצב, ולהפעיל כל הודעה ברגע שהיא מוכנה - בלי לחכות
 * לפריסה ובלי הודעות שקטות בדרך.
 */
const RECORDED = new Set(
  (process.env.YEMOT_RECORDED || "")
    .split(",")
    .map((x) => x.trim())
    .filter(Boolean)
);

/** שרשור כמה הודעות ברצף - מופרדות בנקודה לפי הפרוטוקול */
export function messages(...parts: string[]): string {
  // §69: מיזוג מקטעי הקראה עוקבים.
  //
  // 🐛 מקור ה"גמגום": כל מקטע t- עובר סינתזת TTS *נפרדת* אצל ימות,
  // עם עצירה מורגשת בין מקטע למקטע. תפריט של 8 מוצרים נבנה כ-9
  // מקטעים - ולכן נשמעו 8 עצירות באמצע המשפט, כאילו המערכת מנסה
  // לדבר ולא מצליחה.
  //
  // הפתרון: כל רצף של t- עוקבים מתמזג למקטע אחד, מופרד בפסיקים -
  // סינתזה אחת, הקראה רציפה, והפסיק גם נותן הפוגה טבעית בין
  // הפריטים. הקלטות (f-) ומספרים (n-/d-) נשארים מקטעים נפרדים כי
  // אי אפשר למזג אותם לתוך טקסט.
  //
  // sanitizeTts כבר הסיר נקודות ומקפים מהטקסטים, ולכן המיזוג לא
  // יכול לייצר מפריד-פרוטוקול בטעות.
  const merged: string[] = [];
  for (const part of parts.filter(Boolean)) {
    const prev = merged[merged.length - 1];
    if (prev?.startsWith("t-") && part.startsWith("t-")) {
      const combined = `${prev}${TTS_PAUSE}${part.slice(2)}`;
      // §98: תקרת אורך למקטע ממוזג.
      //
      // 🐛 הניתוק באמצע השמעת רשימת המוצרים: המיזוג של §69 חיבר
      // את כל הפריטים למקטע TTS **אחד**. תפריט של 12 מוצרים עם
      // שמות וכשרויות הגיע ל-350+ תווים בסינתזה אחת, וימות נפלו
      // באמצע ההשמעה - השיחה התנתקה בלי הקשה ובלי timeout.
      //
      // התקרה נותנת את שני הדברים: מקטעים ארוכים דיים כדי שלא
      // יישמע גמגום בין כל פריט, וקצרים דיים כדי שלא יחרגו.
      // הפיצול נעשה **בין** פריטים ולא באמצע משפט.
      if (combined.length <= MAX_TTS_SEGMENT) {
        merged[merged.length - 1] = combined;
        continue;
      }
      // חורג - פותחים מקטע חדש במקום להאריך
      merged.push(part);
      continue;
    }
    merged.push(part);
  }
  return merged.join(".");
}

/**
 * §98: אורך מרבי למקטע הקראה בודד.
 *
 * 200 תווים ≈ 4-5 פריטי תפריט - מספיק כדי שההקראה תזרום, ורחוק
 * מהגבול שבו ימות נופלים.
 *
 * ⚠️ אם יופיעו שוב ניתוקים באמצע השמעה - להוריד את הערך הזה
 * לפני שמחפשים במקום אחר. זו הייתה הסיבה בפעם הקודמת.
 */
const MAX_TTS_SEGMENT = 200;

/**
 * §88: ההפסקה בין פריטים בתוך מקטע הקראה אחד.
 *
 * 🐛 מה שתוקן: המיזוג של §69 חיבר בפסיק בודד, וההקראה רצה בלי
 * נשימה - "להרשמה הקש 1, לבחירת עיר 2" נשמע כמשפט אחד רצוף
 * והמאזין לא הספיק להפריד בין האפשרויות.
 *
 * 🐛 ניסיון שני שנכשל בשטח: נוסה "; , " (נקודה-פסיק). ימות פסלו
 * את התשובה והשיחה **התנתקה** מיד אחרי בחירת מוצר. נקודה-פסיק
 * אינה תו בטוח בפרוטוקול, ולכן היא מוסרת עכשיו ב-sanitizeTts.
 *
 * הפתרון: פסיקים חוזרים בלבד. הפסיק כבר הוכח כבטוח (§69 שודר
 * ופעל, רק מהר מדי), וכמה פסיקים ברצף מאריכים את ההפסקה בלי
 * להכניס שום תו חדש לפרוטוקול.
 *
 * ⚠️ למה לא נקודה: היא מפריד פקודות בפרוטוקול, ו-sanitizeTts
 * מסירה אותה ממילא.
 *
 * לכוונון: להוסיף או להסיר פסיקים כאן. זה המקום היחיד, וזה משפיע
 * על כל התפריטים במערכת. **אין להכניס תווים שאינם פסיק** בלי
 * לבדוק בשיחה אמיתית - תו לא בטוח מנתק את השיחה.
 */
// §175: 🐛 פסיקים רצופים נקראו כתו ולא כהפוגה.
//
// הערך הקודם היה ", , , " - ארבעה פסיקים בין כל פריט. מנוע
// ההקראה של ימות פירש חלק מהם כתו לקריאה, והלקוח שמע אות
// אקראית בין שם העיר להמשך המשפט ("לירושלים H הקש 1").
//
// ⚠️ פסיק אחד נותן את אותה הפוגה בלי הסיכון. אם ההפוגה תתברר
// כקצרה מדי, הדרך הנכונה להאריך אותה היא **מקטע נפרד** ולא
// עוד פסיקים.
const TTS_PAUSE = ", ";

/** השמעת הודעות ואז יציאה/מעבר */
