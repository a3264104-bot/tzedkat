// ─────────────────────────────────────────────────────────────
// קבלת קלט מהמשתמש (read)
// ─────────────────────────────────────────────────────────────

export type ReadOptions = {
  /** שם הפרמטר שיחזור אלינו עם הערך */
  name: string;
  /** מקסימום ספרות */
  max?: number;
  /** מינימום ספרות */
  min?: number;
  /** שניות להמתנה */
  timeout?: number;
  /** איך להשמיע בחזרה את מה שהוקש */
  playback?: "No" | "Number" | "Digits";
  /**
   * האם לבקש אישור אחרי ההקשה.
   * ברירת המחדל של ימות היא כן ("לאישור הקישו 1") - וזה מעצבן
   * בתפריטים של ספרה אחת, ולכן ברירת המחדל שלנו היא לא.
   */
  confirm?: boolean;
  /** אילו מקשים מותרים. למשל "123" או "1.2.3" לרב-ספרתי */
  allowed?: string;
  /** §97: כמה פעמים לחזור על השאלה בלי קלט. ברירת מחדל 2. */
  retries?: number;
};

/**
 * בקשת קלט מהמשתמש.
 * בונה: read=<הודעות>=<שם>,<שימוש-חוזר>,<max>,<min>,<timeout>,<playback>,...
 */
export function read(prompt: string, opts: ReadOptions): string {
  const {
    name,
    max = 2,
    min = 1,
    // §100: ⚠️ המשמעות של timeout **שונה לפי סוג השדה**:
    //
    //   max = 1  → כמה זמן להמתין להקשה. כאן ארוך זה טוב: הלקוח
    //              שומע תפריט, שוקל, ומקיש.
    //
    //   max > 1  → כמה זמן להמתין ל**ספרה נוספת** אחרי שהוקשה
    //              אחת. כאן ארוך זה נורא: הלקוח הקיש "2", והמערכת
    //              שותקת עד שהזמן פג או שהוא מקיש סולמית.
    //
    // 🐛 §97 קבע 20 שניות לכולם, ולכן שדה הכמות "נתקע" אחרי כל
    // הקשה. ברירת המחדל נשארת ארוכה (היא נכונה לתפריטים), אבל
    // כל שדה רב-ספרתי חייב לקבוע timeout קצר במפורש.
    //
    // §97: 20 שניות במקום 7.
    //
    // 🐛 הניתוק שדווח: הלקוח שמע רשימת מוצרים ארוכה, שקל מה לבחור,
    // וכעבור 7 שניות השיחה נותקה. הסיבה: ext.ini מגדיר
    // api_end_goto=hangup, ולכן read שפג בלי קלט **מסיים את
    // השיחה** במקום לחזור על השאלה.
    //
    // 20 שניות נותנות זמן אמיתי לשקול. בשילוב עם retries למטה,
    // לקוח מהוסס שומע את השאלה שוב במקום למצוא את עצמו מנותק.
    timeout = 20,
    playback = "No",
    confirm = false,
    allowed = "",
    // §97: כמה פעמים לחזור על השאלה לפני ויתור. ברירת המחדל של
    // ימות הייתה ריקה, ולכן ניסיון אחד בלבד.
    retries = 2,
  } = opts;

  // §89: 🐛 כאן היה הבאג שהשבית את המערכת הטלפונית.
  //
  // §69 הוסיף "*" לרשימת המקשים המותרים (מיקום 10), והתשובה
  // נראתה כך:  ...=MENU,,1,1,7,No,,,,1234*,,,,,no
  //
  // ימות פסלו את הפרמטר בגלל התו הזה, ולכן **שום מקש לא היה
  // חוקי**: הלקוח הקיש, שמע "בחירה לא חוקית" או בקשת אישור,
  // וכעבור כמה ניסיונות השיחה התנתקה. זה הסביר גם את הכשל
  // בהקלטת השם וגם את הניתוק בבחירת מוצר.
  //
  // ⚠️ וההוספה הייתה מיותרת מלכתחילה: מיקום 7 הוא "חסימת כוכבית",
  // ואנחנו משאירים אותו ריק - כלומר הכוכבית מותרת ממילא כברירת
  // מחדל. הטיפול בערך "*" בראש ה-handler ממשיך לעבוד כרגיל.
  //
  // הלקח: אין להוסיף תווים לרשימת המקשים המותרים. היא מיועדת
  // לספרות בלבד.

  // מיקומי הערכים לפי התיעוד:
  // 1=שם, 2=שימוש חוזר, 3=max, 4=min, 5=timeout, 6=playback,
  // 7=חסימת כוכבית, 8=חסימת אפס, 9=החלפת תו, 10=מקשים מותרים,
  // 11=חזרות, 12=התנהגות בריק, 13=טקסט לריק, 14=מקלדת, 15=אישור
  const parts = [
    name,
    "", // לא להשתמש בערך קודם - כל שאלה נשאלת מחדש
    String(max),
    String(min),
    String(timeout),
    playback,
    "", // כוכבית מותרת
    "", // אפס מותר
    "", // ללא החלפת תווים
    allowed,
    String(retries), // §97: חזרות - במקום ויתור מיידי
    "", // התנהגות בריק - ברירת מחדל
    "", // טקסט לריק
    "", // מקלדת
    confirm ? "" : "no",
  ];
  return `read=${prompt}=${parts.join(",")}`;
}

/**
 * בקשת הקלטה שתתומלל לטקסט (זיהוי דיבור).
 *
 * 🐛 קודם זה נעשה ע"י read() רגיל ואז .replace() על המחרוזת שנוצרה -
 * פתרון שביר שנשבר בשקט אם סדר הערכים משתנה, ואז נשלח max=0 שאינו חוקי.
 * כאן הפורמט נבנה ישירות: <שם>,<שימוש-חוזר>,voice
 */
export function readVoice(prompt: string, name: string): string {
  return `read=${prompt}=${name},,voice`;
}

/** מעבר לשלוחה אחרת */
export function goToFolder(folder: string): string {
  return `go_to_folder=${folder}`;
}

/**
 * סיום השיחה אחרי השמעת הודעה.
 *
 * 🐛 היה כאן `go_to_folder=hangup` - ימות מצפים בפקודה הזו ל*שלוחה*
 * (מספר או נתיב כמו /1), לא למילה "hangup". התוצאה: ימות לא זיהו את
 * התשובה כחוקית והשמיעו M1607 "אין מענה משרת API".
 *
 * הדרך הנכונה: לא להוסיף פקודת ניתוק כלל. אחרי id_list_message ימות
 * מסיימים את השלוחה לבד ומתנהגים לפי api_end_goto (ברירת מחדל: חזרה
 * שלב אחד אחורה). לניתוק מלא מגדירים בשלוחה api_end_goto=hangup.
 */
export function hangup(): string {
  return "";
}

