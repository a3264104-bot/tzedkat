// §280: סימני צורה לפי קטגוריה — מקור אמת יחיד
// ═══════════════════════════════════════════════════════════════
// למה כאן ולא בכל קובץ: הפונקציה נדרשת בשני דפים (חלוקה ומיון),
// ושני עותקים היו מתפצלים ביום שמישהו מוסיף קטגוריה לאחד מהם.
// הנציג היה מקבל דף אחד עם ⬤ ואחד בלי, בלי להבין למה.
//
// ⚠️ צורה ולא צבע: הדפים **מודפסים בשחור-לבן** בפועל, והצבעים
// שבנינו (§161) פשוט נעלמים. צורה נשארת.
//
// ⚠️ למה זה נדרש: ביום החלוקה הנציג מוצא חבילת שניצל ולא יודע
// למי היא שייכת. הוא סורק את הדף ומחפש ⬤ - עשרות תאים הופכים
// לחמישה.

/**
 * הצורה שתופיע לצד שם המוצר.
 *
 * ⚠️ הרגקסים נבדקו מול **שמות הקטגוריות האמיתיים** במסד:
 *   בשר בקר · דגים · עופות טריים · קפואים ומארזים ·
 *   מוצרים מיוחדים / מוגבלים
 *
 * הבדיקה הזו תפסה באג: הגרסה הראשונה חיפשה "עוף" ביחיד,
 * והקטגוריה נקראת "עופות" - כלומר אף עוף לא היה מסומן.
 */
export function categoryMark(
  categoryName: string | null | undefined
): string {
  const c = (categoryName || "").trim();
  if (!c) return "";

  // ⚠️ בשר **לפני** עוף: קטגוריה בשם "בשר עוף" מכילה את שניהם,
  // והבדיקה הראשונה שמתאימה קובעת. בשר הוא הסימון החשוב יותר
  // לנציג, כי הוא היקר.
  if (/בשר|בקר|עגל|כבש/.test(c)) return "■";

  // ⚠️ "עופות" ברבים — זה השם בפועל.
  if (/עופות|עוף|פרג|הודו|כנפ|שניצל|חזה|שוק/.test(c)) return "⬤";

  if (/דגים|סלמון|מושט|בורי|פילה|נסיכה/.test(c)) return "▲";

  // ⚠️ "קפואים ומארזים" היא קטגוריה **מעורבת** - יש בה גם עוף
  // וגם בשר, ואין סימן אחד נכון. ◆ אומר "קרא את השם", והנציג
  // לא מחפש לשווא סימן שאינו קיים.
  if (/קפוא|מארז/.test(c)) return "◆";

  // ⚠️ ריק ולא סימן ברירת מחדל: סימן שגוי גרוע מחוסר סימן.
  // הנציג שרואה ⬤ על בשר מחפש במקום הלא נכון.
  //
  // ⚠️ "מוצרים מיוחדים / מוגבלים" נשארת בלי סימן בכוונה - זו
  // קטגוריה ניהולית, לא סוג סחורה.
  return "";
}

/**
 * המקרא שמוצג בכותרת הדפים.
 *
 * ⚠️ נגזר מאותה פונקציה: מקרא שמזכיר סימן שהפונקציה לא מחזירה
 * שולח את הנציג לחפש משהו שאינו קיים.
 */
export const CATEGORY_LEGEND = "⬤ עופות · ■ בשר · ▲ דגים · ◆ קפוא/מארז";
